/* BB Protector 1.3/INXS */

#include "../unp64.h"
void Scn_BBProt(unpstr *Unp)
{
    unsigned char *mem;
    unsigned char bbphack[]={ /* B6 04 */
     0x78,0xA5,0xAE,0x85,0xFA,0xA5,0xAF,0x85,0xFB,0xC6,0x01,0x4C,0xCF,0x04,
     0xC6,0xFA,0xA5,0xFA,0xC9,0xFF,0xD0,0x02,0xC6,0xFB,0x60,0x20,0xC4,0x04,
     0x20,0xC4,0x04,0xA0,0x00,0xB1,0xFA,0xC8,0x38,0xF1,0xFA,0x88,0x91,0xFA,
     0xA5,0xFB,0xC9,0x08,0xD0,0xEC,0xB9,0x60,0x09,0x99,0x01,0x08,0xC8,0xD0,
     0xF7,0xEE,0xE8,0x04,0xEE,0xEB,0x04,0xAD,0xE8,0x04,0xC9,0xD0,0xD0,0xEA,
     0x8C,0x00,0x08,0xE6,0x01,0x20,0xA3,0xFD,0x2C,0x15,0xFD,0xA9,0xE1,0x8D,
     0x28,0x03,0x58,0x20,0x59,0xA6,0x4C,0xA7,0xAE
    };
    int p,x;
    if ( Unp->IdFlag )
        return;
    mem=Unp->mem;
    if( Unp->DepAdr==0 )
    {
        if( (*(unsigned int*)(mem+0x826)==0x208E00A2) &&
            (*(unsigned int*)(mem+0x82F)==0xAE45084C) &&
            (*(unsigned int*)(mem+0x848)==0x04104CE5)
          )
        {
            /* patch: don't allow to copy the decrypt routine to $0410 */
            mem[0x833]=0x2c;
            mem[0x83b]=0x2c;
            mem[0x840]=0x2c;
            mem[0x843]=0x2c;
            mem[0x84a]=0xb6; /* 04b6  */
            memcpy( mem+0x4b6, bbphack, sizeof(bbphack) );
            Unp->Forced=0x826;
            Unp->DepAdr=0x4b6;
            Unp->RetAdr=0xa7ae;
            Unp->StrMem=0x0801;
            Unp->EndAdr=Unp->info->end-0x160; /* AE/AF must be exactly set */
            if(Unp->DebugP)
            {
                x=(Unp->info->end&0xff);
                for(p=0x84c;p<0x84c+0x10;p++)
                {
                    mem[p] = (mem[p]^x) & 0x7f;
                }
                printmsg(mem,0x84c,0x10);
            }
            PrintInfo(Unp,_I_BBPROT13);
            Unp->IdFlag=1;return;
        }
    }
}

